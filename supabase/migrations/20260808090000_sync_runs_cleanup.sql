-- ============================================================================
-- 부산 Dartrip — 만료 정리 결과를 실행 로그에 남깁니다 (`X-47` · `D-54-2`)
--
-- 설계 정본: `API데이터설계.md` §5.3(`sync_runs` DDL) · §5.7(보존 정책)
--            `lib/sync.ts` `cleanup()` (본 열을 쓰는 유일한 자리)
--
-- 왜 이 열이 필요한가
-- -------------------
-- 증분 크론은 매일 만료분을 지웁니다(§5.7). 그런데 **몇 건을 지웠는지가 어디에도 남지
-- 않았습니다.** 지운 결과가 응답 본문(`SyncOutcome.cleanup`)에만 있고, 그 응답을 받는 것은
-- 크론 스케줄러뿐이라 아무도 읽지 않습니다.
--
-- 그 상태에서 곤란해지는 시점이 **정해져 있습니다** — `throws` 첫 만료가 2026-09-03 이고
-- 1차 심사 제출 마감이 2026-09-21 입니다. 그날 처음 도는 삭제가 잘못 동작해도(0건만 지운다,
-- 지나치게 지운다) 지금 구조로는 **아무 흔적이 없어** 심사 기간에야 드러납니다.
-- 실행 로그에 건수를 남기면 그 다음 날 바로 확인됩니다.
--
-- 왜 열 하나(jsonb)인가
-- ---------------------
-- 정리 대상이 넷(`throws`·`place_enrichment`·`sync_runs`·`rate_limits`)이고 앞으로 늘 수
-- 있습니다. 대상마다 정수 열을 하나씩 두면 대상이 늘 때마다 마이그레이션이 붙고, 그 열들이
-- 전부 `null` 인 과거 행이 쌓입니다. **한 열에 한 실행의 정리 결과 한 덩어리**를 두면
-- 대상이 늘어도 스키마가 그대로입니다.
--
-- 이 값은 집계·정렬에 쓰지 않습니다 — 사람이 되짚어 읽는 기록이라 인덱스도 두지 않습니다.
--
-- `null` 이 뜻하는 것
-- -------------------
-- **"정리가 안 돌았다"** 입니다. 0건을 지운 것과 구분됩니다 — 전자는 `null`, 후자는
-- `{"throws":0,...}` 입니다. 두 가지가 같은 값으로 보이면 "지울 게 없었는지, 코드가
-- 거기까지 못 갔는지" 를 되짚을 수 없습니다. `dryRun` 실행과 정리 전에 끊긴 실패 실행이
-- 여기에 해당합니다.
--
-- 실행 방법
-- ---------
--   Supabase 대시보드 > SQL Editor 에 본 파일 내용을 붙여넣고 Run.
--   여러 번 실행해도 결과가 같습니다.
--
--   **실행 전에도 앱은 그대로 동작합니다** — 열이 없으면 적재에서 이 항목만 빠지고
--   나머지 마무리 기록(`status`·`cursor`·건수)은 종전대로 남습니다(`lib/sync.ts` `finishRun`).
-- ============================================================================

alter table sync_runs
  add column if not exists cleanup jsonb;

comment on column sync_runs.cleanup is
  '이 실행이 만료 정리로 지운 건수 (X-47). null = 정리가 돌지 않음 (0건 삭제와 구분됩니다).';
