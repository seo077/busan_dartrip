-- ============================================================================
-- 부산 Dartrip — 집계표 대조 결과를 실행 로그에 남깁니다 (`X-50`)
--
-- 설계 정본: `API데이터설계.md` §5.3(`sync_runs` DDL) · §6.3 ⑥(주 1회 대조)
--            `lib/sync.ts` `auditPoolStats()` · `finishRun()` (본 열을 쓰는 유일한 자리)
--            바로 앞 선례 = `20260808090000_sync_runs_cleanup.sql` (같은 모양의 열)
--
-- 왜 이 열이 필요한가
-- -------------------
-- `X-47` 이 만료 정리 건수를 `cleanup` 열로 끌어올렸는데, **바로 옆의 같은 구조를 그대로
-- 지나쳤습니다.** 주 1회(월요일) 도는 집계표 대조 결과(`SyncOutcome.audit`)는 여전히
-- **응답 본문에만** 있고, 그 응답을 받는 것은 크론 스케줄러뿐이라 아무도 읽지 않습니다.
--
-- 그래서 곤란한 자리가 하나 생깁니다 — 집계표와 실계수가 맞는지는 **매 회차 손대조**로만
-- 확인되고, **앱 자신이 대조를 돌렸는지조차 확인할 수단이 없습니다.** 백필(08-04) 이후
-- 첫 월요일이 08-10 이라 지금까지 한 번도 돈 적이 없는데, 그 사실과 "돌았는데 결과가
-- 안 남았다" 가 밖에서 구분되지 않습니다.
--
-- 집계표는 다트가 칸을 고르는 근거입니다(§6.4). 그것이 조용히 어긋나면 **다트가 없는
-- 칸을 뽑거나 있는 칸을 빼먹는 방식**으로 드러나는데, 그 실패는 화면에서 정상처럼 보입니다.
-- 대조 결과가 실행 로그에 남으면 그 다음 날 바로 확인됩니다.
--
-- 왜 열 하나(jsonb)인가
-- ---------------------
-- `cleanup` 과 같은 이유입니다 — 대조 결과는 네 값(`compared`·`mismatched`·`repaired`·
-- `samples`)이고 `samples` 는 길이가 정해지지 않은 목록입니다. 정수 열로 펴면 표본을
-- 담을 자리가 없고, 항목이 늘 때마다 마이그레이션이 붙습니다.
--
-- 이 값도 집계·정렬에 쓰지 않습니다 — 사람이 되짚어 읽는 기록이라 인덱스를 두지 않습니다.
--
-- `null` 이 뜻하는 것
-- -------------------
-- **"대조가 안 돌았다"** 입니다. 어긋난 것이 0건인 실행과 구분됩니다 — 전자는 `null`,
-- 후자는 `{"compared":…,"mismatched":0,…}` 입니다. 대조는 **주 1회**라 대부분의 행이
-- `null` 이고, 그것이 정상입니다. 월요일 행이 `null` 이면 그때 되짚을 자리입니다.
--
-- 실행 방법
-- ---------
--   Supabase 대시보드 > SQL Editor 에 본 파일 내용을 붙여넣고 Run.
--   여러 번 실행해도 결과가 같습니다.
--
--   **실행 전에도 앱은 그대로 동작합니다** — 열이 없으면 적재에서 이 항목만 빠지고
--   나머지 마무리 기록(`status`·`cursor`·건수·`cleanup`)은 종전대로 남습니다
--   (`lib/sync.ts` `finishRun` — 없는 열만 하나씩 물러섭니다).
-- ============================================================================

alter table sync_runs
  add column if not exists audit jsonb;

comment on column sync_runs.audit is
  '이 실행의 집계표 대조 결과 (X-50). null = 대조가 돌지 않음 (어긋남 0건과 구분됩니다). 대조는 주 1회(월요일)라 대부분의 행이 null 입니다.';
